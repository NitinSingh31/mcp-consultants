async function seed() {
  try {
    const uri = process.env.MONGODB_URI;
    if (!uri) {
      console.error('No MONGODB_URI found.');
      process.exit(1);
    }
    await mongoose.connect(uri);
    console.log('Connected to MongoDB Atlas.');

    const existingCount = await Candidate.countDocuments();
    console.log(`Current candidates in DB: ${existingCount}`);

    if (existingCount === 0) {
      const inserted = await Candidate.insertMany(sampleCandidates);
      console.log(`Successfully seeded ${inserted.length} candidate profiles into Resdex.`);
    } else {
      console.log('Candidates already present. Ensuring key matching records exist...');
      for (const cand of sampleCandidates) {
        const found = await Candidate.findOne({ email: cand.email });
        if (!found) {
          await Candidate.create(cand);
        }
      }
      const updatedCount = await Candidate.countDocuments();
      console.log(`Total candidates now in DB: ${updatedCount}`);
    }

    await mongoose.disconnect();
    console.log('Seed completed successfully.');
    process.exit(0);
  } catch (err) {
    console.error('Error seeding candidates:', err);
    process.exit(1);
  }
}

seed();
